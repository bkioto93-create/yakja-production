// قابلیت استوری — تصمیم تازه‌ی صریح کارفرما: «فروشنده‌ها/عمده‌فروش‌هایی که VIP می‌خرند باید
// بتوانند ویدئوی استوریِ طولانی‌تر (۳۰ ثانیه به‌جای ۱۵ ثانیه) بگذارند». کاربر معمولی هم‌چنان
// دقیقاً به همان سقفِ قبلیِ ۱۵ ثانیه محدود می‌ماند — هیچ رفتاری برای کاربر غیر-VIP تغییر نکرد.
//
// این ثابت‌ها و تابع کمکی، دقیقاً هم‌الگو با src/lib/vip/vipStatus.ts، عمداً بدون هیچ
// وابستگی به "use client" یا "server-only" نوشته شده‌اند — چون سقفِ مدت‌زمان ویدئو باید هم سمت
// مرورگر (src/lib/stories/storyMediaProcessor.ts، برای تعیین سقفِ فشرده‌سازی/ضبط پیش از آپلود)
// و هم سمت سرور (src/app/[lang]/profile/storyActions.ts، برای اعتبارسنجیِ نهایی و
// غیرقابل‌دورزدنِ درست قبل از insert) از یک منبع حقیقتِ واحد بخوانند — نه دو عددِ جادوییِ
// تکرارشده در دو فایل که ممکن است روزی از هم واگرا شوند (دقیقاً همان درسی که پیش از این فقط با
// یک کامنتِ «این عدد باید دستی هماهنگ بماند» جبران می‌شد؛ این فایل آن هماهنگی دستی را کاملاً
// حذف می‌کند).
export const STORY_VIDEO_MAX_DURATION_SECONDS_FREE = 15;
export const STORY_VIDEO_MAX_DURATION_SECONDS_VIP = 30;

// سقفِ مدت‌زمانِ مجازِ ویدئوی استوری بر اساسِ وضعیتِ VIP کاربر — چه در لحظه‌ی فشرده‌سازیِ
// سمتِ مرورگر (پیش از آپلود) چه در لحظه‌ی اعتبارسنجیِ نهاییِ سمتِ سرور (درست قبل از ثبت در
// دیتابیس) باید همین یک تابع صدا زده شود.
export function getStoryVideoMaxDurationSeconds(isVip: boolean): number {
  return isVip ? STORY_VIDEO_MAX_DURATION_SECONDS_VIP : STORY_VIDEO_MAX_DURATION_SECONDS_FREE;
}